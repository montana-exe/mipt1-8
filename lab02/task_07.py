"""Задание № 7: подсчитать гласные буквы в строке."""

# Строка содержит русские и английские гласные буквы.
VOWELS = "аеёиоуыэюяaeiou"


def count_vowels(text: str) -> int:
    """Вернуть количество гласных без учёта регистра."""
    # Здесь будет храниться количество найденных гласных.
    count = 0

    # lower переводит строку в нижний регистр, затем цикл перебирает буквы.
    for character in text.lower():
        # Проверяем, находится ли очередной символ среди гласных.
        if character in VOWELS:
            # Если символ является гласным, увеличиваем счётчик на один.
            count += 1

    # Возвращаем итоговое количество.
    return count


def main() -> None:
    """Получить строку и вывести количество гласных."""
    # Получаем исходный текст от пользователя.
    text = input("Введите строку: ")
    # Вызываем функцию и сразу печатаем её результат.
    print(f"Количество гласных: {count_vowels(text)}")


if __name__ == "__main__":
    main()

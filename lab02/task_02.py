"""Задание № 2: найти сумму всех нечётных чисел от 1 до N."""


def sum_odd_numbers(n: int) -> int:
    """Вернуть сумму положительных нечётных чисел до N включительно."""
    # В переменной total будем накапливать сумму.
    total = 0

    # Перебираем все целые числа от 1 до N включительно.
    for number in range(1, n + 1):
        # Остаток от деления нечётного числа на 2 равен 1.
        if number % 2 != 0:
            # Прибавляем найденное нечётное число к общей сумме.
            total += number

    # Возвращаем готовый результат из функции.
    return total


def main() -> None:
    """Получить N от пользователя и показать результат."""
    # input получает строку, поэтому int преобразует её в целое число.
    n = int(input("Введите N: "))

    # Вызываем функцию и сохраняем вычисленную сумму.
    result = sum_odd_numbers(n)

    # Выводим результат на экран.
    print(f"Сумма нечётных чисел до {n}: {result}")


# Этот блок выполняется только при прямом запуске данного файла.
if __name__ == "__main__":
    main()

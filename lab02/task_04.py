"""Задание № 4: найти наибольший общий делитель двух чисел."""


def gcd(first: int, second: int) -> int:
    """Вычислить НОД с помощью простого алгоритма Евклида."""
    # abs делает отрицательные числа положительными.
    first = abs(first)
    second = abs(second)

    # Повторяем вычисления, пока второе число не станет нулём.
    while second != 0:
        # Остаток от деления заменяет второе число на следующем шаге.
        remainder = first % second
        # Второе число становится первым.
        first = second
        # Остаток становится вторым числом.
        second = remainder

    # После завершения цикла первое число содержит НОД.
    return first


def main() -> None:
    """Получить два числа и вывести их НОД."""
    # Считываем первое целое число.
    first = int(input("Введите первое число: "))
    # Считываем второе целое число.
    second = int(input("Введите второе число: "))

    # Передаём оба числа в функцию gcd и печатаем ответ.
    print(f"НОД чисел {first} и {second}: {gcd(first, second)}")


if __name__ == "__main__":
    main()

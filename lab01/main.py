"""Лабораторная работа № 1: демонстрационный Python-проект."""


def greeting(name: str = "Git") -> str:
    """Вернуть персонализированное приветствие."""
    # f-строка вставляет полученное имя внутрь текста приветствия.
    return f"Привет, {name}! Проект обновлён."


# Этот блок выполняется только при прямом запуске файла.
if __name__ == "__main__":
    # Вызываем функцию со стандартным именем Git и печатаем результат.
    print(greeting())
